import { chromium } from 'playwright'
const browser=await chromium.launch()
const page=await browser.newPage({viewport:{width:390,height:844}})
const base='https://darkturquoise-duck-750266.hostingersite.com'
await page.goto(base+'/targove?make=BMW&model=X5&site=2',{waitUntil:'networkidle',timeout:60000})
await page.getByRole('button',{name:/^Филтри/}).click()
const form=page.getByRole('form',{name:'Филтри за автомобили'})
await form.locator('[name=year_from]').fill('2015')
await form.locator('[name=year_to]').fill('2016')
await form.locator('[name=fuel]').selectOption('Gasoline')
await form.getByRole('button',{name:'Намери автомобил'}).click()
await page.waitForLoadState('networkidle')
const cards=page.locator('.auction-card')
console.log('MOBILE_FILTER_RESULT',JSON.stringify({url:page.url(),count:await cards.count(),badges:await cards.locator('.car-badge').allTextContents(),titles:await cards.locator('h3').allTextContents(),empty:await page.locator('.empty-state').allTextContents()}))
if(await cards.count()===0)throw new Error('No cards after mobile filter submission')
if((await cards.locator('.car-badge').allTextContents()).some(s=>s!=='IAAI'))throw new Error('Unexpected auction')
if((await cards.locator('h3').allTextContents()).some(s=>!/^201[56] BMW X5/.test(s)))throw new Error('Unexpected year or model')
await browser.close()
