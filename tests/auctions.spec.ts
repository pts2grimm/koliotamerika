import { test, expect } from '@playwright/test'

// External fixture photographs are replaced only in the test browser.
test.beforeEach(async ({ page }) => {
 await page.route('https://cs.copart.com/test-gallery-*.jpg', route => route.fulfill({ path: 'public/images/hero.png', contentType: 'image/png' }))
})
test('homepage carries make/model to auctions and changing make resets model', async ({ page }) => {
 await page.goto('/')
 const search = page.getByRole('form', { name: 'Намери автомобил', exact: true })
 await expect(search.getByRole('combobox', { name: 'Модел', exact: true })).toBeDisabled()
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('BMW')
 await search.getByRole('combobox', { name: 'Модел', exact: true }).selectOption('X5')
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('Ford')
 await expect(search.getByRole('combobox', { name: 'Модел', exact: true })).toHaveValue('')
 await expect(search.locator('select[name="model"] option[value="X5"]')).toHaveCount(0)
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('BMW')
 await search.getByRole('combobox', { name: 'Модел', exact: true }).selectOption('X5')
 await page.screenshot({ path: 'test-results/home-search-desktop.png' })
 await page.setViewportSize({ width: 390, height: 844 })
 await search.scrollIntoViewIfNeeded()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: 'test-results/home-search-mobile.png' })
 await search.getByRole('button', { name: 'Разгледай' }).click()
 await expect(page).toHaveURL(/make=BMW&model=X5/)
 const filters = page.getByRole('form', { name: 'Филтри за автомобили' })
 await expect(filters.getByRole('combobox', { name: 'Марка', exact: true })).toHaveValue('BMW')
 await expect(filters.getByRole('combobox', { name: 'Модел', exact: true })).toHaveValue('X5')
 await expect(page.locator('.auction-card')).toHaveCount(24)
 await expect(page.locator('.auction-card').first()).toContainText('BMW X5')
})
test('auction filters validate years, preserve pagination and remove dependent model', async ({ page }) => {
 await page.goto('/targove?make=BMW&model=X5')
 const filters = page.getByRole('form', { name: 'Филтри за автомобили' })
 await filters.getByLabel('Година от', { exact: true }).fill('2024')
 await filters.getByLabel('Година до', { exact: true }).fill('2022')
 expect(await filters.evaluate((form: HTMLFormElement) => form.checkValidity())).toBe(false)
 await filters.getByLabel('Година от', { exact: true }).fill('2022')
 await filters.getByLabel('Година до', { exact: true }).fill('2024')
 await filters.locator('summary').click()
 await filters.getByRole('combobox', { name: 'Гориво', exact: true }).selectOption('Gasoline')
 await filters.getByRole('button', { name: 'Намери автомобил', exact: true }).click()
 await expect(page.locator('.auction-card')).toHaveCount(24)
 await expect(page.getByRole('link', { name: 'Премахни филтър: Бензин' })).toBeVisible()
 await page.getByRole('navigation', { name: 'Страници с търгове' }).getByRole('link', { name: 'Следваща' }).click()
 await expect(page).toHaveURL(/fuel=Gasoline.*pagenum=2/)
 await expect(page.locator('.auction-card')).toHaveCount(6)
 await page.getByRole('link', { name: 'Премахни филтър: BMW', exact: true }).click()
 await expect(filters.getByRole('combobox', { name: 'Марка', exact: true })).toHaveValue('')
 await expect(filters.getByRole('combobox', { name: 'Модел', exact: true })).toBeDisabled()
 expect(new URL(page.url()).searchParams.has('pagenum')).toBe(false)
 expect(new URL(page.url()).searchParams.has('model')).toBe(false)
 await page.getByRole('link', { name: 'Изчисти всички', exact: true }).click()
 await expect(page).toHaveURL('/targove')
})
test('auction gallery stays on-page, supports keyboard and swipe; related cars exclude current lot', async ({ page }) => {
 await page.goto('/targove/kola?lot=70000000&site=1')
 await expect(page.getByRole('heading', { level: 1 })).toContainText('BMW X5')
 await page.getByRole('button', { name: 'Покажи снимка 2', exact: true }).click()
 await expect(page.locator('.gallery-open img')).toHaveAttribute('src', /test-gallery-2/)
 await page.getByRole('button', { name: 'Увеличи снимка 2' }).click()
 const dialog = page.getByRole('dialog')
 await expect(dialog).toBeVisible()
 await page.keyboard.press('ArrowRight')
 await expect(dialog.locator('output')).toHaveText('3 / 3')
 await dialog.getByRole('button', { name: 'Следваща снимка' }).click()
 await expect(dialog.locator('output')).toHaveText('1 / 3')
 await page.keyboard.press('Escape')
 await expect(dialog).not.toBeVisible()
 await expect(page.getByRole('button', { name: 'Увеличи снимка 1' })).toBeFocused()
 const related = page.getByRole('region', { name: 'Свързани автомобили' })
 await expect(related.locator('.auction-card')).toHaveCount(3)
 await expect(related.locator('a[href="/targove/kola?lot=70000000&site=1"]')).toHaveCount(0)
 for (const title of await related.locator('h3').allTextContents()) expect(title).toContain('BMW X5')
 await page.screenshot({ path: 'test-results/auction-detail-desktop.png', fullPage: true })
 await page.setViewportSize({ width: 390, height: 844 })
 const stage = page.locator('.vehicle-gallery-stage')
 await stage.evaluate(element => {
  const start = new Touch({ identifier: 1, target: element, clientX: 300, clientY: 200 })
  const end = new Touch({ identifier: 1, target: element, clientX: 100, clientY: 210 })
  element.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }))
  element.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }))
 })
 await expect(stage.locator('output')).toHaveText('2 / 3')
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: 'test-results/auction-detail-mobile.png', fullPage: true })
 await page.getByRole('button', { name: 'Увеличи снимка 2' }).click()
 await expect(dialog).toBeVisible()
 await page.screenshot({ path: 'test-results/auction-gallery-mobile.png' })
 await dialog.getByRole('button', { name: 'Затвори галерията' }).click()
 await expect(dialog).not.toBeVisible()
 await expect(page).toHaveURL(/lot=70000000&site=1/)
})
test('auction SEO renders in HTML and filtered URLs remain outside index', async ({ page, request }) => {
 const response = await request.get('/targove')
 const html = await response.text()
 expect(html).toContain('Търгове за коли от Америка — Copart и IAAI')
 expect(html).toContain('Какво включва цената до България')
 await page.goto('/targove')
 await expect(page).toHaveTitle(/Търгове за коли от Америка — Copart и IAAI/)
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'http://localhost:3100/targove')
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'index, follow')
 const schema = await page.locator('script[type="application/ld+json"]').allTextContents()
 const collection = schema.map(value => JSON.parse(value)).find(value => value['@type'] === 'CollectionPage')
 expect(collection.breadcrumb.itemListElement).toHaveLength(2)
 expect(collection.mainEntity.itemListElement).toHaveLength(24)
 await page.screenshot({ path: 'test-results/auctions-desktop.png', fullPage: true })
 await page.goto('/targove?make=BMW&model=X5&site=1,2')
 await expect(page).toHaveTitle(/BMW X5 на търг от Америка/)
 await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, follow')
 await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'http://localhost:3100/targove?make=BMW&model=X5')
 await expect(page.locator('.auction-seo')).toHaveCount(0)
 await page.setViewportSize({ width: 390, height: 844 })
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: 'test-results/auctions-mobile.png' })
})
