test('auction schedules show Bulgarian time, tick without reload and handle missing or invalid dates', async ({ page }) => {
 const errors: string[] = []
 page.on('pageerror', error => errors.push(error.message))
 await page.clock.install({ time: new Date('2030-10-10T11:55:00Z') })
 await page.goto('/targove')
 const scheduled = page.locator('.auction-card').filter({ has: page.locator('a[href="/targove/kola?lot=70000000&site=1"]') })
 await expect(scheduled.locator('.auction-countdown')).toHaveText(/2 дни · 2 ч · [45] мин/)
 await expect(scheduled.locator('time')).toContainText('12.10.2030 г. · 17:00 ч.')
 await expect(scheduled.locator('time')).toHaveAttribute('datetime', '2030-10-12T14:00:00.000Z')
 const missing = page.locator('.auction-card').filter({ has: page.locator('a[href="/targove/kola?lot=70000001&site=1"]') })
 await expect(missing.locator('.auction-countdown')).toHaveText('Очаква се дата')
 await page.setViewportSize({ width: 390, height: 844 })
 await scheduled.scrollIntoViewIfNeeded()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await scheduled.screenshot({ path: 'test-results/auction-schedule-card.png' })
 await page.clock.setSystemTime(new Date('2030-10-12T13:59:30Z'))
 await page.goto('/targove/kola?lot=70000000&site=1')
 const detail = page.locator('.detail-summary > .auction-schedule')
 await expect(detail.locator('.auction-countdown')).toHaveText('Под 1 минута')
 await expect(detail.locator('time')).toContainText('17:00 ч.')
 await page.clock.fastForward(31000)
 await expect(detail.locator('.auction-countdown')).toHaveText('Посоченият час е минал')
 await page.goto('/targove/kola?lot=70000002&site=1')
 await expect(page.getByRole('heading', { level: 1 })).toContainText('BMW X5')
 await expect(page.locator('.detail-summary > .auction-schedule')).toContainText('Очаква се дата')
 expect(errors).toEqual([])
})
