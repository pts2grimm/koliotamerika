test('homepage carries make/model to auctions and changing make resets model', async ({ page }) => {
 await page.goto('/')
 const search = page.getByRole('form', { name: 'Намери автомобил', exact: true })
 await expect(search.locator('select[name=make] option[value=POLARIS]')).toHaveCount(0)
 await expect(search.getByRole('combobox', { name: 'Модел', exact: true })).toBeDisabled()
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('BMW')
 await search.getByRole('combobox', { name: 'Модел', exact: true }).selectOption('X5')
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('Ford')
 await expect(search.getByRole('combobox', { name: 'Модел', exact: true })).toHaveValue('')
 await expect(search.locator('select[name="model"] option[value="X5"]')).toHaveCount(0)
 await search.getByRole('combobox', { name: 'Марка', exact: true }).selectOption('BMW')
 await search.getByRole('combobox', { name: 'Модел', exact: true }).selectOption('X5')
 await page.screenshot({ path: 'test-results/home-search-desktop.png' })
 await page.setViewportSize({ width: 390, height: 844 })
 await search.scrollIntoViewIfNeeded()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: 'test-results/home-search-mobile.png' })
 await search.getByRole('button', { name: 'Разгледай' }).click()
 await expect(page).toHaveURL(/make=BMW&model=X5/)
 await page.getByRole('button', { name: /^Филтри/ }).click()
 const filters = page.getByRole('form', { name: 'Филтри за автомобили' })
 await expect(filters.getByRole('combobox', { name: 'Марка', exact: true })).toHaveValue('BMW')
 await expect(filters.getByRole('combobox', { name: 'Модел', exact: true })).toHaveValue('X5')
 await page.getByRole('button', { name: 'Затвори филтрите' }).click()
 await expect(page.locator('.auction-card')).toHaveCount(24)
 await expect(page.locator('.auction-card').first()).toContainText('BMW X5')
})
