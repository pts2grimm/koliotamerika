import { test,expect } from '@playwright/test'
test('social panel protects admin operations and prepares editable drafts without posting',async({page,request,browser})=>{
 expect((await request.get('/api/admin/social')).status()).toBe(403)
 expect((await request.post('/api/cron/social')).status()).toBe(403)
 const email='social-admin@example.test',password='Social-fixture-only-123'
 expect((await request.post('/api/users/first-register',{data:{email,password}})).status()).toBe(200)
 await page.goto('/admin/login')
 await page.locator('input[name=email]').fill(email);await page.locator('input[name=password]').fill(password)
 await page.getByRole('button',{name:/Вход|Log in|Login/i}).click()
 await expect(page).not.toHaveURL(/\/admin\/login/)
 await page.goto('/admin/social')
 await expect(page.getByRole('heading',{name:'Facebook публикации',exact:true})).toBeVisible()
 await expect(page.getByText('Няма потвърдена Facebook страница')).toBeVisible()
 const origin={origin:'http://localhost:3100'}
 const article=await page.request.post('/api/pages',{headers:origin,data:{title:'Social article fixture',slug:'social-article-fixture',kind:'article',status:'published',intro:'Проверено въведение за теста.',publishedAt:'2026-01-01T00:00:00.000Z'}})
 expect(article.status()).toBe(201)
 expect((await page.request.post('/api/admin/social',{headers:origin,data:{action:'create',kind:'article',source:'social-article-fixture'}})).status()).toBe(200)
 const listResponse=await page.request.get('/api/admin/social?page=1')
 const listBody=await listResponse.json()
 expect(listResponse.status(),JSON.stringify(listBody.error||listBody)).toBe(200)
 const created=listBody.posts.find((p:{kind:string})=>p.kind==='article')
 expect(created.link).toBe('https://koliotamerika.bg/social-article-fixture')
 expect(created.message).toContain('Проверено въведение')
 expect((await page.request.post('/api/admin/social',{headers:origin,data:{action:'create',kind:'article',source:'social-article-fixture'}})).status()).toBe(409)
 await page.getByLabel('Тип',{exact:true}).selectOption('tip')
 await page.getByRole('button',{name:'Проверка преди наддаване',exact:true}).click()
 await page.getByRole('button',{name:'Създай чернова',exact:true}).click()
 const post=page.locator('.koa-social__post').first()
 await expect(post).toContainText('За одобрение')
 await expect(post.getByRole('button',{name:'Одобри за публикуване'})).toBeDisabled()
 await post.getByLabel('Текст на публикацията').fill('Оригинален тестов съвет за проверка на документите.')
 const savedResponse=page.waitForResponse(r=>r.url().endsWith('/api/admin/social')&&r.request().method()==='POST'&&r.request().postDataJSON()?.action==='edit')
 await post.getByRole('button',{name:'Запази като чернова'}).click()
 expect((await savedResponse).ok()).toBe(true)
 await expect(post.getByLabel('Текст на публикацията')).toHaveValue('Оригинален тестов съвет за проверка на документите.')
 await page.reload()
 await expect(post.getByLabel('Текст на публикацията')).toHaveValue('Оригинален тестов съвет за проверка на документите.')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const stateResponse=await page.request.get('/api/admin/social?page=1')
 expect(stateResponse.status()).toBe(200)
 const state=await stateResponse.json()
 expect(state.settings.enabled).toBe(false)
 expect(JSON.stringify(state)).not.toContain('FACEBOOK_PAGE_ACCESS_TOKEN')
 const csrf=await page.request.post('/api/admin/social',{headers:{origin:'https://evil.test'},data:{action:'prepare'}})
 expect(csrf.status()).toBe(403)
 const tip=state.posts[0]
 const approve=await page.request.post('/api/admin/social',{headers:{origin:'http://localhost:3100'},data:{action:'approve',id:tip.id,revision:tip.revision}})
 expect(approve.status()).toBe(400)
 const customerContext=await browser.newContext()
 const customer=await customerContext.request.post('/api/account/register',{headers:{origin:'http://localhost:3100'},data:{email:'social-customer@example.test',name:'Test Customer',password,consent:true}})
 expect(customer.status()).toBe(200)
 expect((await customerContext.request.get('/api/admin/social')).status()).toBe(403)
 await customerContext.close()
})
