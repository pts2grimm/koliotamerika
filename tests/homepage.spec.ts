import {test,expect} from '@playwright/test'
test.afterEach(async({page},info)=>{if(info.status!==info.expectedStatus)console.log('HOME_FIXTURE_UI',page.url(),await page.locator('body').innerText().catch(()=>''))})
test('homepage editor saves sections, metadata and FAQ with admin-only access',async({page,request,browser})=>{
 const origin={origin:'http://localhost:3100'}
 expect((await request.post('/api/globals/homepage',{headers:origin,data:{hero:{title:'Forbidden'}}})).status()).toBe(403)
 const email='home-admin@example.test',password='Home-fixture-only-123'
 expect((await request.post('/api/users/first-register',{data:{email,password}})).status()).toBe(200)
 await page.goto('/admin/login')
 await page.locator('input[name=email]').fill(email);await page.locator('input[name=password]').fill(password)
 await page.getByRole('button',{name:/Вход|Log in|Login/i}).click()
 await expect(page).not.toHaveURL(/\/admin\/login/)
 await page.goto('/admin/globals/homepage')
 await expect(page.getByRole('heading',{name:'Начална страница',exact:true}).first()).toBeVisible()
 // Use the actual Payload form controls and Save workflow.
 const hero=page.locator('.collapsible').filter({has:page.locator('#field-hero__title')})
 if(await hero.count())await hero.first().locator('.collapsible__toggle').click()
 const h1=page.locator('#field-hero__title')
 if(!(await h1.isVisible()))await page.getByText('Първи екран',{exact:true}).first().click()
 await h1.fill('Редактиран първи екран')
 const response=page.waitForResponse(r=>r.url().includes('/api/globals/homepage')&&['POST','PATCH'].includes(r.request().method()))
 await page.getByRole('button',{name:/^(Запази|Save)$/}).first().click()
 expect((await response).ok()).toBe(true)
 await page.reload()
 const stateResponse=await page.request.get('/api/globals/homepage',{headers:origin})
 expect(stateResponse.ok()).toBe(true)
 const state=await stateResponse.json()
 expect(state.hero.title).toBe('Редактиран първи екран')
 expect(state.faq.items.length).toBe(4)
 const patch=await page.request.post('/api/globals/homepage',{headers:origin,data:{seo:{title:'SEO заглавие за проверка',description:'Описание от редактора.'},faq:{items:[]},services:{enabled:false},search:{enabled:false},catalogue:{enabled:false},news:{enabled:false}}})
 expect(patch.ok(),await patch.text()).toBe(true)
 // The public cache is invalidated after the response; TTL also bounds other processes.
 await expect.poll(async()=>{const r=await request.get('/');return (await r.text()).includes('SEO заглавие за проверка')},{timeout:40000}).toBe(true)
 await page.goto('/')
 await expect(page).toHaveTitle('SEO заглавие за проверка')
 await expect(page.locator('h1')).toHaveText('Редактиран първи екран')
 await expect(page.locator('meta[name=description]')).toHaveAttribute('content','Описание от редактора.')
 await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href','http://localhost:3100/')
 expect(await page.locator('.home-service-cards').count()).toBe(0)
 expect(await page.locator('.home-faq details').count()).toBe(0)
 const schemas=await page.locator('script[type="application/ld+json"]').allTextContents()
 expect(schemas.some(s=>s.includes('"FAQPage"'))).toBe(false)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 const customerContext=await browser.newContext()
 expect((await customerContext.request.post('/api/account/register',{headers:origin,data:{email:'home-customer@example.test',name:'Fixture',password,consent:true}})).status()).toBe(200)
 expect((await customerContext.request.post('/api/globals/homepage',{headers:origin,data:{hero:{title:'Forbidden'}}})).status()).toBe(403)
 await customerContext.close()
})
