import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('consented browser actions, inquiries, private report and customer attribution', async ({page,playwright,baseURL})=>{
 const admin=await playwright.request.newContext({baseURL})
 const credentials={email:'catalog-admin@example.test',password:'Catalog-admin-2026'}
 expect((await admin.post('/api/users/first-register',{data:credentials})).ok()).toBeTruthy()
 const login=await admin.post('/api/users/login',{data:credentials})
 const headers={Authorization:'JWT '+(await login.json()).token}
 const records=async()=> (await (await admin.get('/api/catalog-events',{headers,params:{limit:100,sort:'-id'}})).json()).docs
 const origin={Origin:baseURL!}
 const browser=page.context().browser()!
 const context=await browser.newContext({baseURL})
 await context.route('**/*',route=>['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort())
 const visitor=context.request
 const post=(data:object)=>visitor.post('/api/catalog-activity',{headers:origin,data})
 const receipt=randomUUID()
 const data={kind:'search',section:'cars',archive:false,make:'BMW',model:'X5',outcome:'results',resultCount:30,filters:{make:'BMW',model:'X5'}}
 const event={receipt,event:randomUUID(),data}
 expect((await post(event)).status()).toBe(403)
 expect((await visitor.get('/api/catalog-events')).status()).toBe(403)
 expect((await visitor.post('/api/catalog-events',{data})).status()).toBe(403)
 // Operational inquiries must remain visible even when statistics are refused.
 const inquiry=await visitor.post('/api/inquiry',{headers:origin,data:{name:'Без статистика',email:'inquiry@example.test',phone:'+359888123456',car:'BMW X5 · lot 70000000',message:'Искам информация за този автомобил.',consent:true}})
 expect(inquiry.status()).toBe(201)
 expect(await records()).toHaveLength(0)
 const consentCookie=(analytics:boolean)=>({name:'koa-consent',value:encodeURIComponent(JSON.stringify({version:1,analytics,marketing:false,updatedAt:Date.now()})),url:baseURL!})
 await context.addCookies([consentCookie(true)])
 expect((await post(event)).status()).toBe(204)
 expect((await post(event)).status()).toBe(204)
 let rows=await records()
 expect(rows).toHaveLength(1)
 expect(rows[0].subject).not.toBe(receipt)
 expect(rows[0].customer).toBeFalsy()
 expect((await visitor.post('/api/catalog-activity',{headers:{Origin:'https://attacker.example'},data:event})).status()).toBe(403)
 expect((await post({...event,event:randomUUID(),customer:42})).status()).toBe(400)
 expect((await post({...event,event:randomUUID(),data:{...data,query:'private@example.test'}})).status()).toBe(400)
 expect((await post({...event,extra:'x'.repeat(5000)})).status()).toBe(413)
 expect((await admin.patch('/api/catalog-events/'+rows[0].id,{headers,data:{make:'Changed'}})).status()).toBe(403)
 expect((await visitor.post('/api/account/register',{headers:origin,data:{email:'catalog-customer@example.test',password:'Catalog-customer-2026',name:'Клиент за каталог',consent:true}})).ok()).toBeTruthy()
 expect((await post({...event,event:randomUUID(),data:{kind:'view',section:'cars',archive:false,make:'BMW',model:'X5',yearFrom:'2022',lot:'70000000',site:'1'}})).status()).toBe(204)
 rows=await records()
 expect(rows.find((r:{kind:string})=>r.kind==='view').customer.email).toBe('catalog-customer@example.test')
 expect(rows.find((r:{kind:string})=>r.kind==='search').customer).toBeFalsy()
 expect((await visitor.get('/api/catalog-events')).status()).toBe(403)
 // HTML / RSC prefetches execute no browser beacon, even with consent.
 await visitor.get('/targove?make=BMW')
 expect(await records()).toHaveLength(2)
 const fresh=await context.newPage()
 await context.clearCookies()
 let beacons=0
 fresh.on('request',req=>{if(req.url().includes('/api/catalog-activity'))beacons++})
 await fresh.goto('/targove?make=BMW&model=X5')
 await expect(fresh.getByRole('heading',{name:'Ти избираш бисквитките'})).toBeVisible()
 expect(beacons).toBe(0)
 const first=fresh.waitForResponse(r=>r.url().includes('/api/catalog-activity'))
 await fresh.getByRole('button',{name:'Приеми всички',exact:true}).click()
 expect((await first).status()).toBe(204)
 await expect.poll(async()=> (await records()).length).toBe(3)
 // A rendered detail produces one view; React effects / hydrated UI do not duplicate it.
 const view=fresh.waitForResponse(r=>r.url().includes('/api/catalog-activity'))
 await fresh.goto('/targove/kola?lot=70000000&site=1')
 expect((await view).status()).toBe(204)
 await expect.poll(async()=> (await records()).length).toBe(4)
 const empty=fresh.waitForResponse(r=>r.url().includes('/api/catalog-activity'))
 await fresh.goto('/targove?make=Toyota')
 expect((await empty).status()).toBe(204)
 rows=await records()
 expect(rows.find((r:{make:string})=>r.make==='Toyota').outcome).toBe('empty')
 // Refusal stops future navigation records and clears the session identifier.
 await fresh.evaluate(()=>window.dispatchEvent(new Event('koa:cookie-settings')))
 await fresh.getByRole('button',{name:'Само необходимите',exact:true}).click()
 await expect.poll(()=>fresh.evaluate(()=>sessionStorage.getItem('koa-catalog-session'))).toBeNull()
 await fresh.goto('/targove?make=Ford')
 await expect(fresh.getByRole('heading',{level:1})).toBeVisible()
 expect(await records()).toHaveLength(5)
 expect((await post({...event,event:randomUUID()})).status()).toBe(403)
 // Broken analytics cannot prevent the catalogue from rendering.
 await context.addCookies([consentCookie(true)])
 await fresh.route('**/api/catalog-activity',route=>route.abort())
 await fresh.goto('/targove?make=BMW')
 await expect(fresh.getByRole('heading',{level:1})).toBeVisible()
 expect(await records()).toHaveLength(5)
 await context.close()

 await page.goto('/admin/catalog-activity')
 await expect(page).toHaveURL(/\/admin\/login/)
 await page.locator('input[name=email]').fill(credentials.email)
 await page.locator('input[name=password]').fill(credentials.password)
 await page.locator('button[type=submit]').click()
 await page.goto('/admin/catalog-activity')
 await expect(page.getByRole('heading',{name:'Активност в каталога',exact:true})).toBeVisible()
 await expect(page.locator('#catalog-history')).toContainText('5 записа')
 await expect(page.locator('#catalog-inquiries')).toContainText('Без статистика')
 await expect(page.locator('#catalog-history')).toContainText('Клиент за каталог')
 await expect(page.locator('#catalog-history')).toContainText('Без резултати')
 await expect(page.locator('.template-default__wrap')).toHaveCount(1)
 await page.setViewportSize({width:1440,height:1050})
 if(!(await page.locator('.nav--nav-open').count())) await page.locator('button.nav-toggler:visible').first().click()
 await expect(page.locator('#koa-nav-catalog-activity')).toHaveAttribute('aria-current','page')
 await page.screenshot({path:'test-results/catalog-activity-desktop.jpg',type:'jpeg',quality:75})
 await page.locator('#catalog-inquiries').screenshot({path:'test-results/catalog-inquiries.jpg',type:'jpeg',quality:75})
 await page.goto('/admin/catalog-activity?make=Ford')
 await expect(page.locator('#catalog-history')).toContainText('Няма записани действия')
 await expect(page.locator('#catalog-inquiries')).toContainText('Няма запитвания')
 await page.goto('/admin/catalog-activity?kind=view&make=BMW&model=X5')
 await expect(page.locator('#catalog-history')).toContainText('2 записа')
 await expect(page.locator('#catalog-inquiries')).toContainText('Без статистика')
 await page.goto('/admin/catalog-activity?page=99999&inquiryPage=99999')
 await expect(page).toHaveURL(/inquiryPage=1/)
 await expect(page.locator('#catalog-history')).toContainText('5 записа')
 await page.setViewportSize({width:390,height:844})
 if(await page.locator('.nav--nav-open').count()) await page.locator('.nav__mobile-close').click()
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:'test-results/catalog-activity-mobile.jpg',type:'jpeg',quality:75})
 await admin.dispose()
})
