import { test, expect } from '@playwright/test'
import { randomBytes } from 'node:crypto'
const password = randomBytes(24).toString('base64url')
const origin = { origin: 'http://localhost:3100' }
test.beforeAll(async ({ request }) => {
 const response = await request.post('/api/users/first-register', { data: { email: 'account-admin@example.test', password } })
 expect([200, 403]).toContain(response.status())
})
const vehicle = { kind: 'auction', lot: '12345678', site: '1', title: 'BMW X5 — запазен' }
test('customer registration, device sync, private inquiries, access boundaries and logout', async ({ browser }) => {
 const alice = await browser.newContext(); const bob = await browser.newContext(); const device = await browser.newContext()
 try {
  const alicePage = await alice.newPage()
  await alicePage.goto('/registracia')
  await alicePage.getByLabel('Име и фамилия').fill('Алиса Тест')
  await alicePage.getByLabel('Имейл', { exact: true }).fill('alice@example.test')
  await alicePage.getByLabel(/^Парола/).fill(password)
  await alicePage.locator('[name="consent"]').check()
  await alicePage.getByRole('button', { name: 'Създай профил' }).click()
  await expect(alicePage.getByRole('heading', { name: 'Здравей, Алиса Тест.' })).toBeVisible()
  const cookie = (await alice.cookies()).find(c => c.name === 'koa-customer')!
  expect(cookie.httpOnly).toBe(true); expect(cookie.sameSite).toBe('Lax')
  const session = await (await alice.request.get('/api/account')).json()
  expect(session.user.email).toBe('alice@example.test'); expect(session).not.toHaveProperty('token'); expect(session.user).not.toHaveProperty('hash')
  await alicePage.evaluate(v => localStorage.setItem('koa-saved-auctions', JSON.stringify([v])), { lot: vehicle.lot, site: vehicle.site, title: vehicle.title })
  await alicePage.reload()
  await alicePage.getByRole('button', { name: 'Добави ги в профила' }).click()
  await expect(alicePage.getByRole('heading', { name: vehicle.title })).toBeVisible()
  expect(await alicePage.evaluate(() => localStorage.getItem('koa-saved-auctions'))).toBeNull()
  const login = await device.request.post('/api/account/login', { headers: origin, data: { email: 'alice@example.test', password } })
  expect(login.status()).toBe(200); expect(await login.json()).not.toHaveProperty('token')
  expect((await (await device.request.get('/api/account')).json()).saved).toEqual([vehicle])
  // Separate customer cannot read Alice's saved cars or private inquiries.
  const register = await bob.request.post('/api/account/register', { headers: origin, data: { name: 'Боб Тест', email: 'bob@example.test', password, consent: true, role: 'admin' } })
  expect(register.status()).toBe(200)
  expect((await (await bob.request.get('/api/account')).json()).saved).toEqual([])
  for (let attempt = 0; attempt < 2; attempt++) expect((await bob.request.post('/api/account/save', { headers: origin, data: { vehicle, customer: session.user.id } })).status()).toBe(200)
  expect((await (await bob.request.get('/api/account')).json()).saved).toEqual([vehicle])
  const bobID = (await (await bob.request.get('/api/account')).json()).user.id
  const inquiry = await alice.request.post('/api/inquiry', { headers: origin, data: { name: 'Алиса Тест', email: 'bob@example.test', phone: '+359888123456', car: vehicle.title, message: 'Искам повече информация за тази кола.', consent: true, customer: bobID, notes: 'FORGED PRIVATE NOTE' } })
  expect(inquiry.status()).toBe(201)
  const history = await (await alice.request.get('/api/account/inquiries')).json()
  expect(history.docs).toHaveLength(1); expect(history.docs[0].car).toBe(vehicle.title); expect(history.docs[0]).not.toHaveProperty('notes')
  expect((await (await bob.request.get('/api/account/inquiries')).json()).docs).toEqual([])
  // Payload's native APIs must not turn a customer token into staff privileges.
  const auth = { Authorization: `JWT ${cookie.value}` }
  for (const path of ['/api/users', '/api/customers', '/api/inquiries', '/api/saved-vehicles']) expect([401, 403]).toContain((await alice.request.get(path, { headers: auth })).status())
  const cars = await (await alice.request.get('/api/cars', { headers: auth })).json()
  expect(cars.docs.some((c: { status: string }) => c.status === 'draft')).toBe(false)
  for (const slug of ['site-settings', 'calculator-settings']) expect([401, 403]).toContain((await alice.request.post(`/api/globals/${slug}`, { headers: auth, data: { brand: 'HACKED' } })).status())
  const adminCreate = await alice.request.post('/api/users', { headers: auth, data: { email: 'intruder@example.test', password } }); expect([401, 403]).toContain(adminCreate.status())
  for (const action of ['first-register', 'login', 'forgot-password', 'reset-password']) expect((await alice.request.post(`/api/customers/${action}`, { data: { email: 'alice@example.test', password } })).status()).toBe(403)
  const crossSite = await alice.request.post('/api/account/save', { headers: { origin: 'https://other.example' }, data: { vehicle } }); expect(crossSite.status()).toBe(403)
  expect((await alice.request.post('/api/account/save', { headers: origin, data: { vehicle: { kind: 'car', slug: '../admin', title: 'Bad URL' } } })).status()).toBe(400)
  await alicePage.goto('/targove')
  const heart = alicePage.locator('.auction-card').first().getByRole('button', { name: 'Запази автомобила' })
  await heart.click()
  await expect(alicePage.locator('.auction-card').first().getByRole('button', { name: 'Премахни от запазените' })).toHaveAttribute('aria-pressed', 'true')
  await alicePage.locator('.auction-card').first().getByRole('button', { name: 'Премахни от запазените' }).click()
  await expect(heart).toHaveAttribute('aria-pressed', 'false')
  await alicePage.goto('/kontakti'); await expect(alicePage.locator('[name="email"]')).toHaveValue('alice@example.test'); await expect(alicePage.locator('[name="email"]')).toHaveAttribute('readonly', '')
  await alicePage.getByLabel('Телефон', { exact: false }).fill('+359888123456')
  await alicePage.getByLabel('Какво търсиш?').fill('Допълнителна информация за покупка на автомобил.')
  await alicePage.locator('[name="consent"]').check()
  await alicePage.getByRole('button', { name: 'Изпрати запитване' }).click()
  await expect(alicePage.getByRole('link', { name: 'Виж запитванията в профила си' })).toBeVisible()
  await alicePage.getByRole('button', { name: 'Ново запитване' }).click()
  await expect(alicePage.locator('[name="email"]')).toHaveValue('alice@example.test')
  await alicePage.goto('/profil'); await expect(alicePage.getByRole('heading', { name: 'Моите запитвания' })).toBeVisible(); await expect(alicePage.getByText('Искам повече информация за тази кола.')).toBeVisible()
  await alicePage.screenshot({ path: 'test-results/customer-profile-desktop.png', fullPage: true })
  await alicePage.setViewportSize({ width: 390, height: 844 }); expect(await alicePage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await alicePage.screenshot({ path: 'test-results/customer-profile-mobile.png', fullPage: true })
  await alicePage.getByRole('button', { name: 'Изход', exact: true }).click(); await expect(alicePage.getByRole('link', { name: 'Вход', exact: true })).toBeVisible()
  // A copied logged-out cookie must no longer authenticate; the other device stays signed in.
  const replay = await browser.newContext(); await replay.addCookies([cookie])
  expect((await (await replay.request.get('/api/account')).json()).user).toBeNull(); await replay.close()
  expect((await (await device.request.get('/api/account')).json()).user.email).toBe('alice@example.test')
  expect((await device.request.post('/api/account/remove', { headers: origin, data: { vehicle } })).status()).toBe(200)
  expect((await (await device.request.get('/api/account')).json()).saved).toEqual([])
  expect((await (await bob.request.get('/api/account')).json()).saved).toEqual([vehicle])
  // Recover through a local SMTP sink; no mail is sent to an external server.
  const forgot = await alice.request.post('/api/account/forgot', { headers: origin, data: { email: 'alice@example.test' } })
  expect(forgot.status()).toBe(200)
  const outbox = await (await alice.request.get('http://127.0.0.1:3199/test-mail')).json()
  const mail = outbox.messages.find((m: { recipient: string }) => m.recipient.includes('alice@example.test'))
  expect(mail).toBeTruthy()
  const [mailHeaders, ...parts] = mail.message.split('\r\n\r\n')
  const decoded = mailHeaders.includes('Content-Transfer-Encoding: base64') ? Buffer.from(parts.join('\r\n\r\n'), 'base64').toString('utf8') : parts.join('\r\n\r\n').replace(/=\r\n/g, '').replace(/=3D/g, '=')
  const resetToken = decoded.match(/token=([a-f0-9]{40})/)?.[1]
  expect(resetToken).toBeTruthy()
  const newPassword = randomBytes(24).toString('base64url')
  const reset = await alice.request.post('/api/account/reset', { headers: origin, data: { token: resetToken, password: newPassword } })
  expect(reset.status()).toBe(200)
  expect((await (await device.request.get('/api/account')).json()).user).toBeNull()
  expect((await alice.request.post('/api/account/reset', { headers: origin, data: { token: resetToken, password: newPassword } })).status()).toBe(400)
  expect((await device.request.post('/api/account/login', { headers: origin, data: { email: 'alice@example.test', password } })).status()).toBe(401)
  expect((await device.request.post('/api/account/login', { headers: origin, data: { email: 'alice@example.test', password: newPassword } })).status()).toBe(200)
  const graph = await alice.request.post('/api/graphql', { data: { query: '{ Customers { docs { id email } } }' } }); expect([403, 404]).toContain(graph.status())
 } finally { await alice.close(); await bob.close(); await device.close() }
})
