import { test, expect } from '@playwright/test'
// Synthetic 2-second colour/tone fixture, generated with ffmpeg; no real engine recording.
test.beforeEach(async ({ page }) => {
 await page.route('https://cs.copart.com/test-gallery-*.jpg', route => route.fulfill({ path: 'public/images/hero.png', contentType: 'image/png' }))
})
test('engine video is lazy, plays with sound controls and stops on close; photos still work', async ({ page, request }) => {
 let mediaRequests = 0
 await page.route('https://cs.copart.com/test-engine.mp4', route => { mediaRequests++; return route.fulfill({ path: 'tests/fixtures/engine-test.mp4', contentType: 'video/mp4' }) })
 await page.goto('/targove/kola?lot=70000004&site=1')
 const button = page.getByRole('button', { name: 'Пусни видео на двигателя' })
 await expect(button).toBeVisible(); await expect(page.locator('.gallery-thumbnails button').first()).toHaveAttribute('aria-label', 'Пусни видео на двигателя')
 expect(mediaRequests).toBe(0); await expect(page.locator('video')).toHaveCount(0)
 const before = (await (await request.get('http://127.0.0.1:3199/test-requests')).json()).requests.length
 await button.click()
 const dialog = page.getByRole('dialog', { name: /Видео на двигателя/ }); await expect(dialog).toBeVisible()
 const player = dialog.locator('video'); await expect(player).toHaveAttribute('preload', 'none'); await expect(player).toHaveAttribute('playsinline', '')
 expect(mediaRequests).toBe(0)
 await player.evaluate(async (node: HTMLVideoElement) => { await node.play() })
 await expect.poll(() => player.evaluate((node: HTMLVideoElement) => node.currentTime)).toBeGreaterThan(0)
 expect(await player.evaluate((node: HTMLVideoElement) => node.muted)).toBe(false)
 const handle = await player.elementHandle()
 await page.keyboard.press('ArrowRight'); await expect(dialog.locator('video')).toHaveCount(1)
 await page.keyboard.press('Escape'); await expect(dialog).not.toBeVisible()
 expect(await handle!.evaluate((node: HTMLVideoElement) => node.paused)).toBe(true)
 await expect(button).toBeFocused(); await expect(page.locator('video')).toHaveCount(0)
 expect((await (await request.get('http://127.0.0.1:3199/test-requests')).json()).requests.length).toBe(before)
 await page.getByRole('button', { name: 'Увеличи снимка 1' }).click(); await expect(page.getByRole('dialog').locator('img')).toBeVisible(); await page.keyboard.press('Escape')
 await page.setViewportSize({ width: 390, height: 844 }); await button.click()
 await expect(page.getByRole('dialog').locator('video')).toBeVisible()
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: 'test-results/engine-video-mobile.png' })
 await page.getByRole('button', { name: 'Затвори галерията' }).click(); await expect(page.locator('video')).toHaveCount(0)
})
test('missing video, video-only lots, unavailable media and trusted embeds have usable states', async ({ page }) => {
 await page.goto('/targove/kola?lot=70000000&site=1'); await expect(page.getByRole('button', { name: 'Пусни видео на двигателя' })).toHaveCount(0)
 await page.route('https://cs.copart.com/test-engine-broken.mp4', route => route.fulfill({ status: 404, body: '' }))
 await page.goto('/targove/kola?lot=70000006&site=1'); await page.getByRole('button', { name: 'Пусни видео на двигателя' }).click()
 await page.locator('video').evaluate((node: HTMLVideoElement) => node.play().catch(() => {}))
 await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Видеото не може да се възпроизведе')
 await expect(page.getByRole('link', { name: 'Отвори видеото отделно' })).toHaveAttribute('href', 'https://cs.copart.com/test-engine-broken.mp4')
 await page.keyboard.press('Escape')
 await page.goto('/targove/kola?lot=70000007&site=1'); await expect(page.getByRole('button', { name: 'Видео на двигателя', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Пусни видео на двигателя' }).click(); await expect(page.getByRole('dialog').locator('video')).toBeVisible(); await page.keyboard.press('Escape')
 let embeds = 0
 await page.route('https://www.youtube-nocookie.com/embed/abcdefghijk', route => { embeds++; return route.fulfill({ body: '<html><body>Test player</body></html>', contentType: 'text/html' }) })
 await page.goto('/targove/kola?lot=70000005&site=1'); expect(embeds).toBe(0)
 await page.getByRole('button', { name: 'Пусни видео на двигателя' }).click(); await expect(page.getByRole('dialog').locator('iframe')).toHaveAttribute('src', 'https://www.youtube-nocookie.com/embed/abcdefghijk')
 await expect.poll(() => embeds).toBe(1); await page.keyboard.press('Escape'); await expect(page.locator('iframe')).toHaveCount(0)
})
