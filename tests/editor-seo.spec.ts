import {test,expect} from '@playwright/test'
test('SEO analysis updates in native editors, saves privately and works on mobile',async({page,request,browser})=>{
 page.setDefaultTimeout(15000);page.setDefaultNavigationTimeout(30000)
 const adminHTML=await (await request.get('/admin/login')).text()
 const styles=[...adminHTML.matchAll(/<link[^>]+href="([^"]+\\.css[^\"]*)"/g)].map(m=>m[1])
 const sheets=await Promise.all(styles.map(async path=>(await request.get(path)).text()))
 console.log('SEO_CSS_DEPLOYMENT_MARKER',sheets.some(css=>css.includes('.koa-seo-analysis')))
 const origin={origin:'http://localhost:3100'},email='seo-admin@example.test',password='SEO-fixture-only-123'
 expect((await request.post('/api/users/first-register',{data:{email,password}})).status()).toBe(200)
 await page.goto('/admin/login',{waitUntil:'domcontentloaded'})
 await page.locator('input[name=email]').fill(email);await page.locator('input[name=password]').fill(password)
 await page.getByRole('button',{name:/Вход|Log in|Login/i}).click();await expect(page).not.toHaveURL(/\/admin\/login/)
 for(const kind of ['page','article']){
  const data=await (await page.request.get('/api/pages?where[slug][equals]=seo-fixture-'+kind+'&depth=0',{headers:origin})).json()
  const doc=data.docs[0];expect(doc.id).toBeTruthy()
  await page.goto('/admin/collections/pages/'+doc.id,{waitUntil:'domcontentloaded'})
  const panel=page.locator('.koa-seo-analysis')
  await expect(panel).toBeVisible()
  let requests=0
  const count=(r:any)=>{if(r.url().includes('/api/pages'))requests++}
  page.on('request',count)
  await page.locator('#field-focusKeyphrase').fill('Коли от Канада')
  await page.locator('#field-seo__title').fill('Коли от Канада — полезно ръководство')
  await expect(panel.locator('[data-check="phrase-title"]')).toHaveAttribute('data-state','pass')
  await expect(panel.locator('[data-check="phrase-h1"]')).toHaveAttribute('data-state','review')
  await page.locator('#field-title').fill('Коли от Канада')
  await expect(panel.locator('[data-check="phrase-h1"]')).toHaveAttribute('data-state','pass')
  expect(requests).toBe(0);page.off('request',count)
  expect((await (await page.request.get('/api/pages/'+doc.id,{headers:origin})).json()).title).toBe(doc.title)
  const response=page.waitForResponse(r=>r.url().includes('/api/pages/'+doc.id)&&['PATCH','POST'].includes(r.request().method()))
  await page.getByRole('button',{name:/^(Запази|Save)$/}).first().click()
  expect((await response).ok()).toBe(true)
  await page.reload({waitUntil:'domcontentloaded'})
  await expect(page.locator('#field-focusKeyphrase')).toHaveValue('Коли от Канада')
  expect((await (await request.get('/api/pages/'+doc.id)).json()).focusKeyphrase).toBeUndefined()
  expect((await (await request.get('/'+doc.slug)).text()).includes('name="keywords"')).toBe(false)
  await page.setViewportSize({width:390,height:844})
  expect(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBe(true)
  await page.setViewportSize({width:1280,height:900})
 }
 console.log('SEO_BROWSER pages and articles OK')
 await page.goto('/admin/globals/homepage',{waitUntil:'domcontentloaded'})
 await expect(page.locator('#field-focusKeyphrase')).toHaveValue('коли от Америка')
 await expect(page.locator('[data-check="phrase-url"]')).toHaveAttribute('data-state','info')
 await page.locator('#field-focusKeyphrase').fill('Несъществуваща тема')
 await expect(page.locator('[data-check="phrase-h1"]')).toHaveAttribute('data-state','review')
 const homeSave=page.waitForResponse(r=>r.url().includes('/api/globals/homepage')&&['PATCH','POST'].includes(r.request().method()))
 await page.getByRole('button',{name:/^(Запази|Save)$/}).first().click()
 expect((await homeSave).ok()).toBe(true)
 await page.reload({waitUntil:'domcontentloaded'})
 await expect(page.locator('#field-focusKeyphrase')).toHaveValue('Несъществуваща тема')
 expect((await (await request.get('/api/globals/homepage')).json()).focusKeyphrase).toBeUndefined()
 const cars=await (await page.request.get('/api/cars?where[slug][equals]=seo-fixture-car',{headers:origin})).json()
 await page.goto('/admin/collections/cars/'+cars.docs[0].id,{waitUntil:'domcontentloaded'})
 await expect(page.locator('[data-check="phrase-h1"]')).toHaveAttribute('data-state','pass')
 await expect(page.locator('#field-focusKeyphrase')).toHaveValue('Ford Mustang')
 console.log('SEO_BROWSER homepage and cars OK')
 const customer=await browser.newContext()
 expect((await customer.request.post('/api/account/register',{headers:origin,data:{email:'seo-customer@example.test',name:'Fixture',password,consent:true}})).status()).toBe(200)
 expect((await customer.request.post('/api/globals/homepage',{headers:origin,data:{focusKeyphrase:'forbidden'}})).status()).toBe(403)
 expect((await (await customer.request.get('/api/globals/homepage',{headers:origin})).json()).focusKeyphrase).toBeUndefined()
 await customer.close()
})
