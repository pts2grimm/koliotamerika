export function clarifyCopy<T>(value:T):T {
 if(Array.isArray(value)) return value.map(clarifyCopy) as T
 if(value&&typeof value==='object') {
  const result={...value} as Record<string,unknown>
  for(const [key,item] of Object.entries(result)) {
   if(key==='text'&&typeof item==='string') result[key]=clarityReplacements.reduce((text,[before,after])=>text.includes(after)?text:text.replaceAll(before,after),item)
   else if(item&&typeof item==='object') result[key]=clarifyCopy(item)
  }
  return result as T
 }
 return value
}
